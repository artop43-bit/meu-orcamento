TOTAL = sum(len(v) for v in EXAMPLES.values())


def test_accuracy_over_95_percent() -> None:
    misses = [
        (text, expected, keyword_category(text))
        for expected, texts in EXAMPLES.items()
        for text in texts
        if keyword_category(text) != expected
    ]
    accuracy = 1 - len(misses) / TOTAL
    assert accuracy >= 0.95, f"{accuracy:.1%} de acerto; erros: {misses}"


@pytest.mark.parametrize(
    "text", ["xyzzy", "Transferência para João", "Pagamento recebido", "Saque"]
)
def test_unknown_or_neutral_texts_return_none_or_service(text: str) -> None:
    assert keyword_category(text) in (None, "Serviços")


def test_longer_term_wins() -> None:
    assert keyword_category("Mercado Livre") == "Compras"
    assert keyword_category("Mercado") == "Alimentação"
    assert keyword_category("Passeio no parque") == "Lazer"
