"""Vocabulário ampliado da categoria automática (v1.7.6).

Mesmo formato de `category_words.py` (termos sem acento, minúsculos, separados por vírgula).
Estes termos só entram quando o dicionário principal ainda não tem o termo: o que já existia
continua valendo igual. Usado pelo lançamento rápido e pelo Tire sua dúvida.
"""

import re
import unicodedata

MORE: dict[str, str] = {}


def _clean(term: str) -> str:
    """Mesma forma das palavras de uma descrição: sem acento, minúsculas, só letras, números e &."""
    term = unicodedata.normalize("NFKD", term.lower())
    term = "".join(ch for ch in term if not unicodedata.combining(ch))
    return " ".join(part for part in re.split(r"[^a-z0-9&]+", term) if part)


def _add(category: str, text: str) -> None:
    for raw in text.split(","):
        term = _clean(raw)
        if len(term) >= 2:
            MORE.setdefault(term, category)


